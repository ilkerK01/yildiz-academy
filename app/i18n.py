def dil(request) -> str:
    secim = request.cookies.get(CEREZ, "") if request is not None else ""
    return secim if secim in DILLER else VARSAYILAN


def cevir(kod: str, metin: str, **degerler) -> str:
    if kod == "en" and degerler.get("n") == 1 and metin in EN_TEKIL:
        sonuc = EN_TEKIL[metin]
    else:
        sonuc = EN.get(metin, metin) if kod == "en" else metin
    return sonuc.format(**degerler) if degerler else sonuc


def js_metinleri(kod: str) -> dict[str, str]:
    if kod != "en":
        return {}
    return {anahtar: EN[anahtar] for anahtar in JS_ANAHTARLARI}
